// ── Main ─────────────────────────────────────────────────────────────────────
async function main() {
  console.log("Getting Spotify token…");
  const token = await getToken();
  console.log("Token OK. Looking up 25 tracks…\n");

  const sqlLines = [
    "-- Auto-generated by scripts/backfill-album-art.mjs",
    "-- URLs verified via Spotify Search API — safe to re-run.",
    "",
  ];

  let found = 0;
  let missing = 0;

  for (const seed of SEEDS) {
    process.stdout.write(`  ${seed.id}  ${seed.title} — ${seed.artist} … `);
    try {
      const { artUrl } = await lookupTrack(token, seed.title, seed.artist);
      if (artUrl) {
        process.stdout.write(`✓\n`);
        sqlLines.push(
          `UPDATE public.songs SET album_art_url = '${artUrl}' WHERE spotify_id = '${seed.id}'; -- ${seed.title}`
        );
        found++;
      } else {
        process.stdout.write(`✗ not found\n`);
        sqlLines.push(`-- NOT FOUND: ${seed.id} (${seed.title} — ${seed.artist})`);
        missing++;
      }
    } catch (err) {
      process.stdout.write(`✗ error: ${err.message}\n`);
      sqlLines.push(`-- ERROR: ${seed.id} (${seed.title}) — ${err.message}`);
      missing++;
    }
  }

  const sql = sqlLines.join("\n") + "\n";
  const outPath = join(ROOT, "supabase", "backfill_album_art.sql");
  writeFileSync(outPath, sql);

  console.log(`\n${found} found, ${missing} missing`);
  console.log(`\nWrote: supabase/backfill_album_art.sql`);
  console.log("Next step: paste that file into Supabase SQL Editor and run it.");
}

main().catch((err) => { console.error(err); process.exit(1); });
